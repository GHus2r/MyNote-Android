    fun toInitials(s: String): String {
        val sb = StringBuilder()
        for (ch in s) {
            when {
                ch in 'a'..'z' -> sb.append(ch)
                ch in 'A'..'Z' -> sb.append(ch.lowercaseChar())
                ch in '0'..'9' -> sb.append(ch)
                else -> map[ch.code]?.let { sb.append(it) }
            }
        }
        return sb.toString()
    }
